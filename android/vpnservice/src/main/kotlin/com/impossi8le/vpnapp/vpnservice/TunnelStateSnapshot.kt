package com.impossi8le.vpnapp.vpnservice

/**
 * Последнее известное состояние туннеля — для плитки «Быстрых настроек».
 *
 * **Почему статический снимок.** `TileService` — системная служба: она
 * запускается в том же процессе, но отдельно от UI, и к первому
 * `onStartListening` графа приложения может ещё не быть. Прочитать состояние у
 * сервиса туннеля ей нечем: `TileService` не может привязаться к `VpnService` и
 * спросить. Снимок нужен именно в момент открытия шторки, и рассылка
 * состояний широковещанием его не заменит — вещание разовое, а шторку открывают
 * в произвольный момент, когда предыдущее уже улетело.
 *
 * Лежит в `:vpnservice`, а не в `:app`: писать сюда должен СЕРВИС, а `:vpnservice`
 * не зависит от `:app` — обратной зависимости быть не может. Обратный порядок
 * (снимок в `:app`) не собрался бы вовсе.
 *
 * Тот же приём, что у [VpnTunnelService.sharedLogBuffer]: один экземпляр на
 * процесс (в манифесте нет `android:process`), поэтому оба видят одно.
 */
object TunnelStateSnapshot {

    /**
     * Имя состояния (`SystemState.name`) или `null`, если его ещё не было.
     *
     * `null` — именно «не знаем», а не «отключено»: плитка обязана отличать
     * эти случаи, иначе после перезапуска процесса покажет выключенным уже
     * поднятый туннель.
     */
    @Volatile
    var stateName: String? = null

    /**
     * Состояние в терминах плитки.
     *
     * Отдельным перечислением, а не `SystemState`: у плитки нет `FAILED`-текста
     * и нет смысла в `CONNECTING` как отдельном действии, а связывать её с
     * внутренним типом сервиса значит тащить в системную службу лишнее.
     */
    enum class State { Unknown, Connected, Connecting, Disconnected }

    fun read(): State = when (stateName) {
        // Поднятый туннель. `ESTABLISHED` — это ровно «интерфейс поднят», и
        // плитка говорит о туннеле, а не о защите: §6 запрещает обещать больше.
        "ESTABLISHED" -> State.Connected
        "CONNECTING" -> State.Connecting
        "IDLE", "LOST", "FAILED" -> State.Disconnected
        // Незнакомую строку считаем незнанием, а не «выключено».
        else -> State.Unknown
    }
}
