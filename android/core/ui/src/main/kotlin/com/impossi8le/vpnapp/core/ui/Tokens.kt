package com.impossi8le.vpnapp.core.ui

import androidx.compose.ui.graphics.Color

/**
 * Токены дизайна, дословно из `docs/design/mockup.html`.
 *
 * Тёмная тема — единственная, и это решение UX-ревью, а не временное упрощение.
 * Светлую тему нельзя добавить «как улучшение» без новой причины.
 *
 * Отдельно про смысл цвета, потому что здесь легко ошибиться:
 *  - [Green] — ТОЛЬКО подтверждённая защита. Не «подключено», не «туннель
 *    поднят», а именно результат замера. Именно ложный зелёный на экране
 *    проверки был главным дефектом, найденным на ревью макета;
 *  - [Amber] — только идущий процесс (подключение, проверка). Ничего другого;
 *  - [Red] — только реальная опасность. Не «ошибка ввода», не «нет сети»;
 *  - у бренда своего цвета нет: основная кнопка белая, [Ice] служит
 *    исключительно для выделения и фокуса.
 */
object VpnColors {
    // Поверхности: от самого глубокого к самому светлому.
    val Void = Color(0xFF0A0C10)
    val Carbon = Color(0xFF12151B)
    val Obsidian = Color(0xFF1A1E26)

    // Границы.
    val Hairline = Color(0xFF262B34)
    val Smoke = Color(0xFF333A45)
    val Edge = Color(0xFF5A6472)

    // Текст: от самого тихого к основному.
    val Ash = Color(0xFF7F8A99)
    val TextSecondary = Color(0xFF8B95A3)
    val Mist = Color(0xFFAAB4C2)
    val Bone = Color(0xFFE8ECF2)

    /** Акцент выделения и фокуса. НЕ брендовый цвет и НЕ индикатор состояния. */
    val Ice = Color(0xFF6FB3FF)

    /** Подтверждённая защита. Единственное место, где уместен зелёный. */
    val Green = Color(0xFF3DDC97)

    /** Идущий процесс: подключение, проверка. Больше нигде. */
    val Amber = Color(0xFFFFB454)

    /** Реальная опасность. Больше нигде. */
    val Red = Color(0xFFFF5F6D)
}

/** Радиусы скруглений из макета. */
object VpnRadii {
    val Card = 14
    val Button = 12
    val Small = 8
}
