package com.impossi8le.vpnapp.core.ui

/**
 * Какие экраны обязаны защищаться от съёмки и копирования.
 *
 * Зачем это моделью, а не вызовом `FLAG_SECURE` в каждом экране: требование
 * легко забыть на новом экране, и забывается оно молча — приложение работает,
 * а код или токен видны в превью недавних задач, в скриншоте и в записи экрана.
 * Как данные требование проверяется тестом и попадает в ревью.
 *
 * `FLAG_SECURE` убирает окно из превью recents, запрещает скриншоты и запись
 * экрана. Он НЕ защищает от съёмки другим устройством — это надо честно
 * называть, а не выдавать за полную защиту.
 */
enum class SecureScreen {
    /** Ввод кода из бота: на экране `device_nonce`, который замыкает вход. */
    NONCE_ENTRY,

    /** Просмотр профиля: внутри приватный ключ. */
    PROFILE_VIEW,

    /** Список подключений и главный экран: секретов нет. */
    HOME,
    CONFIGS,
}

/**
 * Политика защиты экранов.
 *
 * Решение вынесено в значение, чтобы на него мог опереться и UI, и тест.
 */
object ScreenSecurity {

    /**
     * Требуется ли `FLAG_SECURE`.
     *
     * Главный экран и список подключений защищать НЕ нужно: там нет секретов,
     * а запрет скриншотов мешал бы пользователю делиться состоянием с поддержкой.
     * Защита всего подряд обесценивает саму защиту — правило, которое стоит
     * держать в одном месте.
     */
    fun requiresSecureFlag(screen: SecureScreen): Boolean = when (screen) {
        SecureScreen.NONCE_ENTRY -> true
        SecureScreen.PROFILE_VIEW -> true
        SecureScreen.HOME -> false
        SecureScreen.CONFIGS -> false
    }

    /** Экраны, которые обязаны защищаться. */
    val secureScreens: Set<SecureScreen>
        get() = SecureScreen.entries.filterTo(mutableSetOf()) { requiresSecureFlag(it) }

    /**
     * Допустимо ли логировать содержимое экрана.
     *
     * Отдельно от флага: окно может быть защищено от съёмки, но содержимое всё
     * равно уйдёт в лог, если его туда напечатать.
     */
    fun mayLogContent(screen: SecureScreen): Boolean = !requiresSecureFlag(screen)
}
