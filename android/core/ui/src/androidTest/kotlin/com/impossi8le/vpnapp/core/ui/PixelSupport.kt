package com.impossi8le.vpnapp.core.ui

import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.toPixelMap
import androidx.compose.ui.test.SemanticsNodeInteraction
import androidx.compose.ui.test.captureToImage

/**
 * Разбор отрисованных пикселей.
 *
 * Зачем это вообще нужно. Ошибка, которую здесь ловят, — не «не тот оттенок», а
 * «зелёное там, где защиты нет». Такое нельзя доказать семантикой: `RingTone`
 * приходит в `StatusRings` параметром, и проверка «вызывающий передал Protected»
 * уже сделана на JVM. Здесь проверяется то, чего на JVM не видно: что сама
 * отрисовка не подмешивает зелёный от себя и что цвет на экране следует за
 * тоном, а не захардкожен.
 *
 * **Определение цвета — по соотношению каналов, а не по яркости.** Кольца
 * рисуются полупрозрачными (`Green.copy(alpha = 0.30f)`) поверх тёмного фона, и
 * на экране от чистого оттенка остаётся сильно разбавленное пятно: янтарный
 * приходит как (108, 79, 43), где ни один канал не похож на исходные 255/180/84.
 * Проверка «канал ярче порога» на таком кадре не сработала бы никогда, а
 * проверка точного равенства ломалась бы антиалиасией — штрих 1dp на любом
 * экране размыт, и оттенок края сдвинут на единицы.
 *
 * Поэтому сравнивается ЗНАК разности каналов, и это устойчиво к разбавлению:
 * зелёный остаётся «зелёнее красного и синего» при любом альфа-канале, и наоборот.
 * Устойчивое сравнение здесь важнее строгого: тест, падающий на исправном коде,
 * дороже отсутствия теста.
 */
internal fun ImageBitmap.argbPixels(): IntArray = toPixelMap().buffer

/** Пиксели узла целиком: то, что реально нарисовано, а не то, что заявлено. */
internal fun SemanticsNodeInteraction.capturedPixels(): IntArray = captureToImage().argbPixels()

internal fun Int.red(): Int = (this shr 16) and 0xFF
internal fun Int.green(): Int = (this shr 8) and 0xFF
internal fun Int.blue(): Int = this and 0xFF
internal fun Int.alpha(): Int = (this ushr 24) and 0xFF

/**
 * Пиксель, читающийся как зелёный.
 *
 * `VpnColors.Green` (61, 220, 151) даёт зелёный канал заметно выше обоих
 * остальных — и в чистом виде, и разбавленным. Акцент `Ice` (111, 179, 255) сюда
 * НЕ попадает: у него синий выше зелёного, и акцент выделения не должен
 * читаться как признак защиты. Нейтральный `Mist` (170, 180, 194) и `Bone`
 * (232, 236, 242) — тоже: у них синий не ниже зелёного.
 */
internal fun Int.isGreen(): Boolean =
    green() - red() >= GREEN_MARGIN && green() - blue() >= GREEN_MARGIN && green() >= FAINT

/**
 * Пиксель, читающийся как красный.
 *
 * От янтарного красный отличается не «силой красного», а положением зелёного
 * канала. После разбавления опасный красный (255, 95, 109) приходит как
 * (93, 40, 48) — зелёный здесь НИЖЕ синего. Янтарный (255, 180, 84) приходит
 * как (83, 62, 36) — зелёный заметно выше. Разделять их по одному лишь
 * «насколько красный» нельзя: у янтарной рамки разность красного с зелёным (21)
 * больше, чем у красной поверхности (13), и любое правило «краснее — значит
 * красный» путало бы предупреждение с опасностью.
 */
internal fun Int.isRed(): Boolean = red() - green() >= RED_MARGIN && green() - blue() <= RED_BLUE_MAX

/** Пиксель, читающийся как янтарный: зелёный выше синего, но ниже красного. */
internal fun Int.isAmber(): Boolean =
    red() - green() >= AMBER_MARGIN && green() - blue() >= AMBER_BLUE_MIN

/**
 * Пиксель с тёплым (красноватым или желтоватым) оттенком.
 *
 * Мягче [isRed] и [isAmber]: нужен, чтобы отличить предупреждение от нейтрального
 * фона, где хватает самого знака разности. Красный и янтарный различаются
 * отдельными предикатами — смешивать их здесь нельзя, иначе «опасность» и
 * «внимание» снова стали бы неотличимы.
 */
internal fun Int.isRedTinted(): Boolean = red() - green() >= TINT_MARGIN && red() >= FAINT

/**
 * Нижняя граница «вообще видно».
 *
 * Отсекает почти чёрные пиксели: у них каналы сближаются в шуме, и случайный
 * перевес одного канала на пару единиц не означает оттенка. Порог низкий —
 * полупрозрачные штрихи после разбавления лежат в районе 40–110.
 */
private const val FAINT = 28

/** Пиксель, читающийся как акцент выделения (Ice). Не индикатор состояния. */
internal fun Int.isAccentBlue(): Boolean =
    blue() - green() >= ACCENT_MARGIN && green() - red() >= ACCENT_MARGIN

/**
 * Нарисовано ли здесь что-то поверх фона.
 *
 * Фон приложения — `VpnColors.Void` (10, 12, 16), и любой элемент интерфейса
 * светлее его. Порог низкий намеренно: тонкие полупрозрачные кольца и рамки
 * отличаются от фона на единицы, но отличаются.
 */
internal fun Int.isPainted(): Boolean = red() + green() + blue() >= PAINTED_SUM

internal fun IntArray.anyPixel(predicate: (Int) -> Boolean): Boolean = any(predicate)

internal fun IntArray.countPixels(predicate: (Int) -> Boolean): Int = count(predicate)

/** Сколько пикселей вообще нарисовано: кадр не пустой и не сплошной фон. */
internal fun IntArray.countPainted(): Int = countPixels { it.isPainted() }

internal fun IntArray.sameAs(other: IntArray): Boolean = contentEquals(other)

// Пороги подобраны по фактическим разбавленным значениям, снятым с устройства
// (SM-G988U1, Android 13), а не «на глаз» по константам палитры.
//   зелёный   (25, 74, 57) и (33, 106, 77)   — запас 17…49 при пороге 12
//   янтарный  (108, 79, 43)                  — запас 29 и 36 при пороге 15
//   красный   (93, 40, 48)                   — запас 53, зелёный ниже синего
// Различие красный/янтарный держится на знаке «зелёный минус синий»: у красного
// он отрицателен, у янтарного положителен и велик.
private const val GREEN_MARGIN = 12
private const val RED_MARGIN = 25
private const val RED_BLUE_MAX = -4
private const val AMBER_MARGIN = 15
private const val AMBER_BLUE_MIN = 15
private const val TINT_MARGIN = 12
private const val ACCENT_MARGIN = 18

/**
 * Сумма каналов тёмного фона (`Void`) — 38. Порог выше него, но невысок: рамки
 * рисуются в полпикселя и полупрозрачными, и после разбавления их пиксели
 * отличаются от фона всего на несколько единиц. Требовать «заметно светлее»
 * значило бы объявлять нарисованную рамку пустотой.
 */
private const val PAINTED_SUM = 48
