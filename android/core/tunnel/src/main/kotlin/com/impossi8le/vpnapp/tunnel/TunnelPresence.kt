package com.impossi8le.vpnapp.tunnel

/**
 * Есть ли прямо сейчас в системе VPN-туннель — ФАКТ, а не наше мнение о нём.
 *
 * Зачем это отдельно от [SystemState]. `ESTABLISHED` — это событие ядра однажды:
 * ядро сказало «подключено» и умолкло. Пока событие считалось правдой без
 * срока годности, экран оставался в «Подключено» даже после того, как систему
 * снесла интерфейс, а сервис пережил отзыв: `ip route` в этот момент отправлял
 * весь трафик открытым через `wlan0` (см.
 * `docs/testing/2026-10-06-connected-without-tunnel.md`). Это тот же класс
 * ошибки, что запрещает §6: состояние выведено из флага, а не из проверяемого
 * факта.
 *
 * [UNKNOWN] — не «нет», а «спросить не удалось». Различие принципиально: принять
 * сбой опроса за исчезновение значило бы рубить исправный туннель из-за
 * случайного исключения. Неизвестность безопасна — она оставляет состояние как
 * есть, а не переводит в отключено.
 */
enum class TunnelPresence { PRESENT, ABSENT, UNKNOWN }

/**
 * Отвечает на один вопрос: существует ли VPN-интерфейс прямо сейчас.
 *
 * Интерфейсом, а не прямым чтением системы в сторожевом цикле, — по той же
 * причине, по которой проба защиты отделена от её решения: ответ даёт платформа,
 * а решение принимается чистой функцией, которую можно проверить без телефона.
 *
 * Реализация для Android — [AndroidTunnelPresence]; в тестах — фейк.
 */
fun interface TunnelPresenceProbe {
    fun read(): TunnelPresence
}
