package com.impossi8le.vpnapp.domain.protection

import com.impossi8le.vpnapp.domain.tunnel.TunnelCounters

/** Что удалось измерить о прохождении трафика через туннель по двум снимкам счётчиков. */
enum class TrafficVerdict {
    /**
     * Полный круг: данные вошли в туннель и вернулись через него.
     *
     * Это ИЗМЕРЕННЫЙ факт прохождения, а не конфигурация: подтверждается дельтами
     * счётчиков ядра в обе стороны, а не тем, что приложение само записало в
     * `Builder`.
     */
    RoundTrip,

    /**
     * Наблюдается вход без ответа дольше окна: в туннель что-то ушло (или ядро
     * сообщило об ошибках), но обратно ничего не пришло.
     *
     * Для защиты это знак проблемы, но НЕ её доказательство: сеть могла просто
     * задержать ответ, а эгресс-трафик в это время шёл в обход.
     */
    NoReturn,

    /** Ничего не двигалось: судить не о чем. Это простой, а не поломка. */
    Idle,

    /** Данных мало: окно короткое или счётчики сброшены. Вывод невозможен. */
    Inconclusive,
}

/**
 * «Ходит ли трафик через туннель» — по двум снимкам счётчиков ядра.
 *
 * **Почему это не [com.impossi8le.vpnapp.domain.tunnel.TunnelStallDetection].**
 * Там вопрос «пора ли перезапускать», здесь — «состоялся ли измеренный круг».
 * Признаки похожи, а разумный консерватизм у них ПРОТИВОПОЛОЖНЫЙ, и сводить их
 * в одну функцию нельзя:
 *  - детектору залипания сброс счётчиков надо считать живым (`Flowing`): свежий
 *    туннель заведомо здоров, а перезапуск там ничего не портит;
 *  - здесь сброс счётчиков — это ОТСУТСТВИЕ данных ([Inconclusive]), а не
 *    доказательство круга: подтверждать «трафик идёт» тем, что счётчики
 *    обнулились, значит выводить зелёное из ничего.
 *
 * **Граница честности (читать до использования вердикта).** [TrafficVerdict.RoundTrip]
 * доказывает, что через tun-интерфейс прошёл измеренный трафик в обе стороны — то
 * есть, что ядро работает и что-то через него действительно ходит. Он НЕ
 * доказывает: что через туннель идёт трафик ПОЛЬЗОВАТЕЛЯ, а не служебный
 * (keepalive, чужой процесс); что приложение не исключено из перехвата
 * (per-UID-исключение в счётчиках tun не видно); что не утекли DNS/DoH и IPv6
 * (эти данные идут мимо tun и в счётчиках tun не отражены). Поэтому вердикт
 * RoundTrip — утверждение О ТУННЕЛЕ, а не о защите. Превращать его в
 * `ProtectionEvidence` (три истины ipv4/ipv6/dns) нельзя: счётчики их не
 * измеряют, и такое зелёное было бы ровно той ложной уверенностью, против
 * которой написан §6.
 */
object TrafficObservation {

    /**
     * Минимальное окно замера.
     *
     * Меньше — не судим вовсе. За короткое окно круг может не успеть состояться
     * просто потому, что пользователь молчит, и [TrafficVerdict.NoReturn] был бы
     * ошибкой; период опроса залипания — 15 с, поэтому 30 с это два опроса, но не
     * доказательство «за время окна ничего не пришло».
     */
    const val MIN_WINDOW_MILLIS = 30_000L

    /**
     * Сколько секунд без принятого пакета считать отсутствием ответа.
     *
     * Если байты уходят, а ответа не было дольше этого — вердикт [TrafficVerdict.NoReturn].
     * Тот же порядок, что у порога залипания (90 с): раньше судить нельзя, поведение
     * приложения при этом не меняем.
     */
    const val NO_RETURN_AFTER_MILLIS = 90_000L

    /**
     * Вердикт по двум снимкам счётчиков.
     *
     * @param minWindowMillis длина окна, меньше которой вывод невозможен.
     */
    fun observe(
        before: TunnelCounters,
        after: TunnelCounters,
        minWindowMillis: Long = MIN_WINDOW_MILLIS,
    ): TrafficVerdict {
        val elapsed = after.takenAtMillis - before.takenAtMillis
        val bytesOutDelta = after.bytesOut - before.bytesOut
        val bytesInDelta = after.bytesIn - before.bytesIn
        val errorsDelta = after.errorsOut - before.errorsOut

        // Сброс счётчиков (перезапуск ядра, новая сессия): сравнивать не с чем.
        // В отличие от детектора залипания, это НЕ «жив» — это «не знаем».
        if (bytesOutDelta < 0 || bytesInDelta < 0 || errorsDelta < 0) {
            return TrafficVerdict.Inconclusive
        }

        // Окно слишком короткое: круг мог не состояться из-за тишины, а не поломки.
        if (elapsed < minWindowMillis) return TrafficVerdict.Inconclusive

        // В обе стороны внутри окна — это и есть доказательство круга.
        if (bytesOutDelta > 0 && bytesInDelta > 0) return TrafficVerdict.RoundTrip

        val sentSomething = bytesOutDelta > 0 || errorsDelta > 0
        val gotSomethingBack = bytesInDelta > 0 ||
            after.lastPacketReceivedAtMillis > before.lastPacketReceivedAtMillis

        // Ушло, а обратно ничего и давно — единственный случай, когда мы говорим
        // о проблеме. «Давно» — по последнему принятому пакету, а не по часам
        // окна: ядро знает точнее, приходил ли ответ. Свежий пакет даёт возраст
        // около нуля и сюда не попадает — так и задумано.
        if (sentSomething && !gotSomethingBack &&
            after.takenAtMillis - after.lastPacketReceivedAtMillis >= NO_RETURN_AFTER_MILLIS
        ) {
            return TrafficVerdict.NoReturn
        }

        // Всё остальное — тишина или недостаточно однозначная картина.
        return TrafficVerdict.Idle
    }
}
