package com.impossi8le.vpnapp.domain.protection

import kotlin.time.Duration
import kotlin.time.Duration.Companion.seconds

/**
 * Когда перепроверять защиту.
 *
 * Однократное подтверждение устаревает само по себе: сеть меняется, интерфейс
 * перезапускается, ядро может потерять рукопожатие. Зелёное без перепроверки —
 * это «зелёное навсегда», что хуже отсутствия индикатора: пользователь уверен
 * в защите, которой уже нет.
 *
 * Политика вынесена сюда как данные, потому что решение «пора ли перепроверить»
 * — чистая функция от времени и событий, и его надо проверять тестом, а не
 * наблюдением.
 */
data class ReverificationPolicy(
    /**
     * Периодическая перепроверка. Не чаще, чем нужно: замер — это сетевые
     * обращения, и слишком частый опрос сам создаёт нагрузку и утечки.
     */
    val interval: Duration = 60.seconds,

    /**
     * Перепроверять немедленно при смене сети. Роуминг — самый частый случай,
     * когда зелёное перестаёт быть правдой без единого признака в UI.
     */
    val onNetworkChange: Boolean = true,

    /**
     * Сбрасывать ли подтверждение сразу при событии, не дожидаясь результата
     * нового замера. `true` означает: между событием и вердиктом экран показывает
     * «не проверено», а не старое зелёное. Это безопаснее — лучше показать
     * неизвестность, чем подтверждение, которого уже нет.
     */
    val clearBeforeReverify: Boolean = true,
) {
    init {
        require(interval.isPositive()) { "интервал перепроверки должен быть положительным" }
        require(interval >= 5.seconds) {
            "интервал $interval слишком мал: замер делает сетевые обращения, и частый опрос сам становится проблемой"
        }
    }

    companion object {
        /** Политика по умолчанию: раз в минуту и по событию смены сети. */
        val Default = ReverificationPolicy()
    }
}
