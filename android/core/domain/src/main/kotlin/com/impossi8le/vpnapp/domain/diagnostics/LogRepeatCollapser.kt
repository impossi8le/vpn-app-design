package com.impossi8le.vpnapp.domain.diagnostics

/**
 * Схлопывание повторов одинаковых строк журнала ядра.
 *
 * **Зачем.** При потере сети ядро пишет одно и то же без остановки:
 * `UDP send exception: send: Network is unreachable` сотни раз за сессию
 * (в отчётах 04.11 — 916 и 1493 строки). Буфер ограничен по строкам, поэтому эти
 * повторы вытесняют рукопожатие, смену узлов и причину обрыва — то есть ровно
 * то, ради чего отчёт и отправляют (issue #66).
 *
 * **Что делает.** Подряд идущие одинаковые строки пропускает один раз, а при
 * смене строки или по завершении дописывает «… повторено N раз». Пустые строки
 * между повторами не считаются разрывом: ядро вставляет их в свой вывод.
 *
 * **Почему отдельный тип.** Это чистое решение, проверяемое тестом; сервис лишь
 * вызывает [accept] и [flush].
 */
class LogRepeatCollapser {

    private var last: String? = null
    private var count = 0

    /**
     * Решение по очередной строке.
     *
     * `null` — писать нечего (повтор). Иначе — что писать сейчас; при смене
     * строки это может быть хвост про повторы предыдущей.
     */
    fun accept(line: String): String? {
        // Пустая строка — разделитель в выводе ядра, а не новое содержимое.
        if (line.isBlank()) {
            if (last == null) return line
            // Копим: настоящий разрыв покажет следующая непустая строка.
            return null
        }
        if (line == last) {
            count++
            return null
        }
        val tail = summary()
        last = line
        count = 1
        return if (tail == null) line else tail + "\n" + line
    }

    /** Хвост про накопленные повторы; `null`, если повтор один или нет вовсе. */
    fun summary(): String? =
        if (count > 1) "… повторено ${count - 1} раз" else null

    /** Чем закончить поток: хвост про последнюю серию, если она была. */
    fun flush(): String? = summary()
}