package com.impossi8le.vpnapp.domain.protection

/**
 * Сырые факты о сетевом линке, сведённые к простым данным.
 *
 * Граница проходит здесь, и это принципиально. Платформенный код (Android) умеет
 * только ЧИТАТЬ маршруты и DNS и складывать их сюда. Всё решение о защите
 * принимает [evaluateFacts] — чистая функция, которую можно проверить на JVM
 * целиком, без эмулятора.
 *
 * Поэтому без устройства непроверенной остаётся одна тонкая функция-заполнитель,
 * а не вся логика §6.
 */
data class LinkFacts(
    /** Маршруты вида «адрес/длина префикса», как их отдаёт система. */
    val routes: List<String>,
    val dnsServers: List<String>,
)

/**
 * Чистое решение о защите по фактам линка.
 *
 * ВАЖНО, и это надо знать, читая код: эти три признака читаются из активного
 * линка, а когда туннель поднят, активный линк — и есть VPN-сеть. То есть
 * признаки в значительной степени описывают конфигурацию, которую приложение
 * само записало в `VpnService.Builder`, а не то, что трафик действительно идёт.
 *
 * Что это ловит: забытый маршрут `::/0`, не переданный в `Builder` DNS, снятый
 * перехват IPv4.
 * Чего это НЕ ловит: самоисключение приложения из перехвата (per-UID исключение
 * в таблице маршрутов не отражается), подмену DNS на уровне Private DNS/DoH,
 * и упавшее рукопожатие OpenVPN с уже установленными маршрутами.
 *
 * Дополняется отдельным замером эгресса — см. §6 архитектуры и открытый вопрос §14.
 */
fun evaluateFacts(
    facts: LinkFacts,
    tunnelDns: List<String>,
): ProtectionVerdict {
    val routeSet = facts.routes.map { it.trim() }.toSet()

    val ipv4InTunnel = routeSet.contains("0.0.0.0/0")
    // Закрытым IPv6 считается только при явном маршруте: отсутствие настройки
    // не блокировка, и система может продолжать выпускать IPv6 в обход.
    val ipv6Closed = routeSet.contains("::/0")
    // Сверяется КАЖДЫЙ DNS профиля: частичное совпадение означает, что часть
    // запросов может уйти системному резолверу.
    val dnsInside = tunnelDns.isNotEmpty() &&
        tunnelDns.all { it.trim() in facts.dnsServers.map(String::trim) }

    return ProtectionVerdict.evaluate(ipv4InTunnel, ipv6Closed, dnsInside)
}
