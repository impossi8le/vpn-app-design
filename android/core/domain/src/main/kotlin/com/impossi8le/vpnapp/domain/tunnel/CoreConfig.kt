package com.impossi8le.vpnapp.domain.tunnel

/**
 * Настройки ядра OpenVPN, которые приложение передаёт движку.
 *
 * Единственный параметр — уровень логирования, и он ограничен жёстко.
 * При `verb >= 3` ядро печатает тела PEM: приватный ключ, полученный из
 * профиля, оказывается в logcat. Оттуда его забирает любой, у кого есть доступ
 * к логам, крэш-отчёту или отладочному мосту — секрет утекает, не покидая
 * устройство официально.
 *
 * Проверка стоит в конструкторе, а не в комментарии: собрать опасный конфиг
 * физически невозможно.
 *
 * ВАЖНО: **опасное значение приходит из профиля, а не из нашего кода.** Реальный
 * боевой `.ovpn` этого проекта содержит `verb 3`. Поэтому одного конструктора
 * мало — нужен единственный вход для значений из профиля, который понижает
 * уровень, а не пробрасывает его. См. [fromProfile].
 */
class CoreConfig(val verb: Int = 1) {

    init {
        require(verb in 0..1) {
            "verb=$verb недопустим: при verb >= 3 OpenVPN печатает тела PEM, и приватный ключ уезжает в logcat"
        }
    }

    companion object {
        /**
         * Уровень логирования, при котором OpenVPN печатает тела PEM.
         * Порог назван, чтобы не разбрасывать магическое «3» по коду.
         */
        const val PEM_PRINTING_VERB = 3

        /** Верхняя граница, которую мы готовы пропустить в ядро. */
        const val SAFE_MAX_VERB = 1

        /**
         * Конфиг по значению из профиля.
         *
         * **Уровень профиля не пробрасывается, а понижается.** Профиль приходит
         * с сервера и содержит `verb 3`; пропустить это значение — значит
         * печатать приватный ключ в logcat при каждом запуске. Значения выше
         * [SAFE_MAX_VERB] заменяются на безопасный максимум, отрицательные — на 0.
         *
         * @param profileVerb значение `verb` из `.ovpn`, если оно там есть.
         */
        fun fromProfile(profileVerb: Int?): CoreConfig {
            val safe = when {
                profileVerb == null -> SAFE_MAX_VERB
                profileVerb < 0 -> 0
                profileVerb > SAFE_MAX_VERB -> SAFE_MAX_VERB
                else -> profileVerb
            }
            return CoreConfig(verb = safe)
        }
    }
}
