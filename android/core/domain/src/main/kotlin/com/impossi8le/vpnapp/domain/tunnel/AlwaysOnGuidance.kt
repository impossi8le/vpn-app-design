package com.impossi8le.vpnapp.domain.tunnel

import com.impossi8le.vpnapp.domain.model.ConnectionStatus

/**
 * Подсказка пользователю про Always-on VPN.
 *
 * Зачем это моделью: у приложения НЕТ киллсвитча уровня ОС. `setBlocking(true)`
 * блокирует трафик, только пока жив интерфейс; когда система убивает
 * foreground-сервис (нехватка памяти, свайп из недавних, лимиты на долгие
 * сервисы), туннель падает вместе с блокировкой, и весь трафик немедленно уходит
 * открытым. Единственная защита, переживающая смерть сервиса, — настройка
 * **Always-on VPN** вместе с **«Блокировать соединения без VPN»**, и включает её
 * пользователь в системных настройках, а не приложение.
 *
 * Молчать об этом — значит оставить пользователя в уверенности, что защита
 * переживёт падение сервиса. Поэтому подсказка выдаётся кодом, а не абзацем в
 * документации, который никто не прочитает.
 */
enum class AlwaysOnHint {
    /** Подсказать не нужно: защита не активна, или подсказка уже была. */
    NONE,

    /** Показать предложение настроить Always-on VPN. */
    SUGGEST,
}

object AlwaysOnGuidance {

    /**
     * Нужно ли предложить Always-on VPN.
     *
     * Условия:
     *  - защита подтверждена (`Protected`) — предлагать настройку тому, у кого
     *    туннель не работает, бессмысленно и пугает;
     *  - предложение ещё не отклонено пользователем. Навязчивость здесь вредна:
     *    пользователь пришёл за VPN, а не за настройкой системы;
     *  - система не сообщила, что настройка уже включена.
     *
     * @param status текущее состояние соединения
     * @param alreadyEnabled Always-on VPN для нашего профиля уже включён
     * @param dismissed пользователь уже отклонил предложение
     */
    fun hint(
        status: ConnectionStatus,
        alreadyEnabled: Boolean,
        dismissed: Boolean,
    ): AlwaysOnHint = when {
        alreadyEnabled -> AlwaysOnHint.NONE
        dismissed -> AlwaysOnHint.NONE
        // Только на подтверждённой защите: тогда предложение имеет смысл.
        status.isProtected -> AlwaysOnHint.SUGGEST
        else -> AlwaysOnHint.NONE
    }
}
