package com.impossi8le.vpnapp.domain.settings

import com.impossi8le.vpnapp.domain.tunnel.AlwaysOnHint

/**
 * Несекретные пользовательские настройки.
 *
 * Отдельно от [com.impossi8le.vpnapp.domain.auth.SessionStore]: здесь только
 * предпочтения интерфейса, и хранить их в зашифрованном виде незачем — шифрование
 * защищает приватный ключ и сессию, а «подтверждать ли смену страны» секретом не
 * является. Держать их в одном хранилище значило бы платить расшифровкой на
 * каждый кадр и размывать границу «что считается секретом».
 *
 * Интерфейс в домене, реализация — платформенная (SharedPreferences в `:app`):
 * так решение «что показывать» тестируется на JVM без Android.
 */
interface AppSettingsStore {
    /** Показывать ли подтверждение перед сменой страны. По умолчанию — да. */
    var confirmCountrySwitch: Boolean

    /** Пользователь выбрал «Больше не спрашивать» в шите подтверждения. */
    var dontAskCountrySwitch: Boolean

    /**
     * Пользователь отклонил подсказку включить Always-on VPN.
     *
     * Хранится, а не живёт в памяти экрана: подсказка возвращается при каждом
     * подключении, и отклонённая заново предлагалась бы после каждого запуска —
     * это не «напоминание», а навязчивость.
     */
    var alwaysOnHintDismissed: Boolean
}

/**
 * Показывать ли подсказку про Always-on VPN.
 *
 * **Почему это не `AlwaysOnGuidance.hint`.** Здесь решается ТОЛЬКО вопрос
 * хранения отказа, который на JVM не проверить; само правило «когда предлагать»
 * остаётся в домене ([AlwaysOnGuidance]). Смешивать их значило бы завести две
 * копии правила — и разойтись им при первой же правке.
 */
fun shouldSuggestAlwaysOn(
    hint: AlwaysOnHint,
    dismissed: Boolean,
): Boolean = hint == AlwaysOnHint.SUGGEST && !dismissed

/**
 * Нужно ли спрашивать подтверждение перед сменой страны.
 *
 * Чистая функция, а не условие в разметке: это решение, и его проверяют тестом
 * без рендера. Вопрос задаётся, только если тумблер в аккаунте включён И
 * пользователь не отказался от вопроса галочкой «Больше не спрашивать». Любое
 * из двух условий снимает диалог: тумблер — общий переключатель, галочка —
 * разовый отказ от конкретного подтверждения.
 */
fun askBeforeCountrySwitch(
    confirmCountrySwitch: Boolean,
    dontAskAgain: Boolean,
): Boolean = confirmCountrySwitch && !dontAskAgain
