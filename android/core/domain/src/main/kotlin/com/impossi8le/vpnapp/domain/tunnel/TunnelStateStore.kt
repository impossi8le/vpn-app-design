package com.impossi8le.vpnapp.domain.tunnel

import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow

/**
 * Состояние туннеля на уровне платформы — общий источник правды для всех, кто
 * показывает его независимо от экрана.
 *
 * **Зачем отдельный тип, а не `ConnectionStatus`.** Здесь лежит только то, что
 * знает система: поднимается, поднят, опущен. Защиты тут нет по построению —
 * зелёный статус собирается единственным конструктором из замера `ProtectionGate`
 * (§6), и путать «туннель поднят» с «защищено» нельзя даже именем поля.
 *
 * **Почему именно общий предмет, а не широковещание.** Широковещание разовое:
 * плитка «Быстрых настроек» открывается в произвольный момент, когда прежнее
 * событие уже улетело. Поэтому её состояние обязано жить там, где его видно в
 * любой момент, — и там же, где его пишет тот, кто о состоянии знает.
 *
 * **Почему в `core:domain`.** Писать сюда должны и сервис (`:vpnservice`), и
 * контроллер со сторожем существования туннеля (`:core:tunnel`), а читать — и
 * плитка (`:app`). Единственный модуль, который виден всем трём, — домен;
 * `:core:tunnel` зависит от `:vpnservice` ровно наоборот и обратной зависимости
 * иметь не может (§4.5). Снимок, лежавший в `:vpnservice`, был доступен сервису и
 * плитке, но НЕ контроллеру — и когда сторож гасил туннель, снимок оставался
 * «поднят»: экран говорил «не подключено», плитка — «подключён». Это и есть
 * расхождение, ради которого предмет переехал сюда.
 *
 * **Граница с §6.** Ни один метод не принимает `ConnectionStatus`: снаружи сюда
 * попадает только системный факт. Так плитка физически не может показать защиту,
 * которой не измерял.
 */
object TunnelStateStore {

    private val _state = MutableStateFlow(TunnelState.Unknown)

    /**
     * Текущее состояние. `Unknown` до первого сообщения сервиса, и это НЕ
     * «выключено»: процесс мог только подняться, а туннель — уже работать.
     */
    val state: StateFlow<TunnelState> = _state.asStateFlow()

    /**
     * Опубликовать состояние.
     *
     * Звать её обязаны строго те, кто в этот же момент сообщает состояние экрану:
     * сервис — перед широковещанием, контроллер — когда сторож существования
     * гасит туннель. Разойдясь, писатели дадут плитку, противоречащую экрану.
     */
    fun publish(state: TunnelState) {
        _state.value = state
    }
}

/**
 * Состояние туннеля без доменной защиты.
 *
 * `Recovering` отделён от `Connecting` намеренно: пользователь уже видел
 * «подключено», и показать ему обычное «подключается» значило бы скрыть, что
 * связь пропадала.
 */
enum class TunnelState {
    /** Сервис ещё ничего не сообщал в этом процессе. Не «выключено». */
    Unknown,

    /** Туннеля нет. */
    Idle,

    /** Идёт поднятие, интерфейса ещё нет. */
    Connecting,

    /** Связь пропадала и восстанавливается. */
    Recovering,

    /** Интерфейс поднят. Не значит «защищено» — §6. */
    Established,
}
