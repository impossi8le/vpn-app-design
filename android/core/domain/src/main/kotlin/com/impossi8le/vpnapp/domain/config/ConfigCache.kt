package com.impossi8le.vpnapp.domain.config

/**
 * Локальный кэш последнего успешного ответа `/me`.
 *
 * **Зачем.** Список подключений нужен с первого кадра: пока он грузится из сети,
 * экран пуст, и пользователь, зашедший подключиться, ждёт. Кэш кладёт на экран
 * то, что сервер уже говорил, а сеть догоняет в фоне.
 *
 * **Это НЕ источник истины о свежести.** Кэш — память о прошлом ответе, и выдать
 * его за текущий список нельзя (§6): экран обязан быть помечен как показывающий
 * сохранённые данные, пока обновление не пришло. См. `stalenessNote` в
 * `feature:home`.
 *
 * Реализация живёт в `core:config` (файл в приватном каталоге приложения) —
 * здесь только контракт, чтобы домен и экран не зависели от файловой системы.
 * `load` не бросает: отсутствие или повреждение файла — это «кэша нет», а не
 * повод уронить экран.
 */
interface SubscriptionCache {
    /** Последний сохранённый список или `null`, если кэша нет/он испорчен. */
    fun load(): ConfigList?

    /** Сохранить успешный ответ. Ошибка записи не важна: сеть ответит снова. */
    fun save(list: ConfigList)

    /** Стереть кэш — при выходе из аккаунта, чтобы не показать чужой список. */
    fun clear()
}

/**
 * Что из кэша можно показать на первом кадре.
 *
 * @property configs действующие подключения из кэша, выделенные для экрана.
 * @property fromCache был ли показан хотя бы один конфиг из кэша. `true`
 *   означает, что список на экране — сохранённый, и по нему нельзя утверждать
 *   свежесть; также по нему безопасно восстанавливать счётчики аккаунта.
 */
data class CachedConfigs(
    val configs: List<ConfigSummary>,
    val fromCache: Boolean,
)

/**
 * Отобрать из сохранённого списка то, что показываем на первом кадре, — по
 * ЛОКАЛЬНОЙ дате, без обращения к сети.
 *
 * «Действующее» решается здесь по двум признакам сразу: статус, который сервер
 * прислал в прошлый раз, И срок, который мог истечь уже после того ответа.
 * Только по статусу нельзя — сохранённый `ACTIVE` переживёт собственный
 * `end_date`, и экран предложил бы выбрать то, что уже кончилось (ровно та
 * ложная доступность, против которой написан `toRowState` в `feature:home`).
 * Только по дате нельзя тоже: отозванный (`REVOKED`) конфиг живёт до срока, но
 * не работает.
 *
 * Порядок сервера сохраняется: сортировка — решение представления, и делать его
 * здесь значило бы завести вторую точку зрения на порядок.
 *
 * @param nowEpochSeconds «сейчас» — параметром, а не из часов внутри: иначе
 *   функция перестала бы быть чистой и детерминированной в тесте.
 */
fun cachedConfigSelection(
    cache: ConfigList?,
    nowEpochSeconds: Long,
): CachedConfigs {
    if (cache == null) return CachedConfigs(emptyList(), fromCache = false)
    val usable = cache.configs.filter { it.isUsableAt(nowEpochSeconds) }
    // Пустой кэш (или кэш целиком просроченный) — это «данных нет», а не
    // «данные из кэша»: восстанавливать по нему счётчики аккаунта значило бы
    // утверждать о подписке то, чего мы не знаем.
    return CachedConfigs(usable, fromCache = usable.isNotEmpty())
}

/**
 * Годен ли сохранённый конфиг прямо сейчас.
 *
 * Отдельная чистая функция, а не строка внутри фильтра: это и есть правило
 * «когда скрывать конфиг по дате», и его проверяет тест, а не рендер.
 */
private fun ConfigSummary.isUsableAt(nowEpochSeconds: Long): Boolean =
    status == SubscriptionStatus.ACTIVE && endDateEpochSeconds > nowEpochSeconds
