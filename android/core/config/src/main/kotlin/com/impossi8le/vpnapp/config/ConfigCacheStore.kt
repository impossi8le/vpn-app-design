package com.impossi8le.vpnapp.config

import com.impossi8le.vpnapp.domain.config.ConfigList

/**
 * Что записать в кэш после попытки обновления списка, — чистая функция.
 *
 * Правило одно и оно про §6: **неудачное обновление НЕ затирает кэш.** Сеть
 * отвалилась, сервер ответил 500, сессия истекла — всё это поводы сказать «не
 * удалось», но не поводы потерять последний известный хороший список. Стёртый
 * кэш означал бы, что после одной сетевой ошибки на холодном старте экран
 * пуст, — то есть ровно то, от чего кэш и заводится.
 *
 * Вынесено отдельной функцией, а не парой строк в `MainActivity`: это решение
 * «хоронить данные или нет», и его проверяет тест, а не рука на телефоне.
 *
 * @param current то, что лежит в кэше сейчас (может быть `null` — кэша нет).
 * @param fetched результат обращения к серверу: список при успехе, `null` при
 *   любой неудаче.
 * @return новый список для кэша или `current` без изменений. `null` означает
 *   «в кэше пусто» — и это не новая запись, а сохранение прежнего состояния.
 */
fun cacheAfterRefresh(current: ConfigList?, fetched: ConfigList?): ConfigList? =
    fetched ?: current
