package com.impossi8le.vpnapp.vpnengine

/**
 * Просьбы ядра к платформе о настройке интерфейса.
 *
 * Интерфейс существует, чтобы `net.openvpn.ovpn3` не протекал наружу: реализация
 * моста живёт в `:vpnservice`, где есть `VpnService`, а обёртка ядра работает с
 * этим интерфейсом и о `Builder` не знает. Иначе движок пророс бы в UI и тесты,
 * и заменить его стало бы нельзя.
 *
 * Методы совпадают с `ClientAPI_TunBuilderBase` один в один по смыслу. Имена
 * намеренно наши: если ядро однажды сменится, менять придётся одну реализацию,
 * а не весь код вокруг.
 *
 * **Проверить этот интерфейс тестом нельзя, и это не упущение.** За ним стоит
 * `VpnService.Builder.establish()`, которому система выделяет файловый
 * дескриптор — без живого сервиса вызов не работает. Проверка «конфигурация
 * не бросила исключение» существовала бы отдельно от кода.
 */
interface TunBridge {
    /** Начать настройку: сбросить прошлое состояние. */
    fun new(): Boolean

    /**
     * Адрес удалённой стороны туннеля.
     *
     * На Android это НЕ нужно: `VpnService.Builder` не принимает адрес сервера —
     * маршрутизацией занимается система. Но метод обязан возвращать `true`, и
     * вот почему: его базовая реализация отдаёт `false`, а ядро считает `false`
     * отказом и рвёт установку туннеля с `tun_builder_set_remote_address failed`.
     *
     * Именно на этом падал наш туннель: сервер уже был найден, TLS-рукопожатие
     * прошло, сессия стала активной — и всё обрывалось на создании интерфейса
     * из-за непереопределённого метода, который на Android не делает ничего.
     */
    fun setRemoteAddress(address: String, ipv6: Boolean): Boolean

    fun setMtu(mtu: Int): Boolean

    fun addAddress(address: String, prefixLength: Int, ipv6: Boolean): Boolean

    fun addRoute(address: String, prefixLength: Int, ipv6: Boolean): Boolean

    fun addDns(address: String): Boolean

    /** Перехват трафика по умолчанию — `redirect-gateway` из профиля. */
    fun rerouteGw(ipv4: Boolean, ipv6: Boolean, flags: Long): Boolean

    /**
     * Разрешить DNS вне туннеля.
     *
     * Должно оставаться `false`. `true` означает, что часть запросов уходит
     * системному резолверу мимо туннеля — та же утечка, что незакрытый IPv6.
     */
    fun setAllowLocalDns(allow: Boolean): Boolean

    /**
     * Поднять интерфейс и вернуть его файловый дескриптор.
     *
     * Отрицательное значение означает отказ — например, пользователь не дал
     * согласия на VPN. Ядро такое значение поймёт как сбой.
     */
    fun establish(): Int

    /** Просить сохранять интерфейс между переподключениями. */
    fun persist(): Boolean

    /** Разобрать интерфейс. */
    fun teardown(disconnect: Boolean)

    /**
     * Защитить сокет ядра от ухода мимо туннеля.
     *
     * На Android это `VpnService.protect(fd)`. Без защиты сокет ядра может
     * уйти наружу — то есть утечка, ради исключения которой всё и делается.
     *
     * Возвращать `true` без реальной защиты нельзя: ядро сочтёт сокет
     * защищённым и продолжит работу, а трафик пойдёт мимо туннеля.
     */
    fun protectSocket(socket: Int): Boolean
}
