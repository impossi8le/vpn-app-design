/**
 * Уведомление о лицензии ядра, как его показывать.
 *
 * Текст ядро отдаёт само (`ClientAPI_OpenVPNClientHelper.copyright()`), и мы
 * показываем его БЕЗ правок: переписанное руками уведомление разъехалось бы с
 * ядром при первом же его обновлении.
 */
sealed interface EngineLicenseNotice {

    /** Текст, полученный от ядра. Показывается как есть. */
    data class Text(val text: String) : EngineLicenseNotice

    /**
     * Ядро недоступно или текст не получен.
     *
     * **Причина вместо лицензии, а не выдуманный текст.** На JVM-тестах и в
     * сборке без артефакта движка `libovpn3.so` не загружается, и подставить
     * «правильное» уведомление значило бы выдать за факт то, чего библиотека не
     * сообщала.
     */
    data class Unavailable(val reason: String) : EngineLicenseNotice
}

/** Пометка, что полные тексты лицензий живут в самих библиотеках, а не тут. */
const val LICENSES_FOOTNOTE =
    "Полные тексты лицензий не перепечатаны здесь целиком: они принадлежат " +
        "самим библиотекам и приводятся в их исходных кодах."

/**
 * Собрать уведомление ядра для экрана.
 *
 * Чистая функция — почему так, а не «просто подставить текст в композабл»:
 * решение «показывать текст или причину» должно проверяться тестом, без
 * устройства и без нативной библиотеки.
 *
 * Пустой [text] трактуется как «текста нет», а не как «показать пустоту»:
 * пустая строка на месте уведомления читалась бы как «лицензия не нужна».
 *
 * @param text текст от ядра, или `null`, если ядро недоступно;
 * @param unavailableReason причина, которую показать вместо текста.
 */
fun engineLicenseNotice(text: String?, unavailableReason: String): EngineLicenseNotice =
    if (text.isNullOrBlank()) {
        EngineLicenseNotice.Unavailable(unavailableReason)
    } else {
        EngineLicenseNotice.Text(text)
    }
