package com.impossi8le.vpnapp.feature.home

import androidx.compose.ui.graphics.Color
import com.impossi8le.vpnapp.core.ui.RingTone
import com.impossi8le.vpnapp.core.ui.VpnColors
import com.impossi8le.vpnapp.domain.model.ConnectionStatus

/**
 * Что показать на главном экране для текущего состояния.
 *
 * Отдельный тип, а не разметка внутри Composable: это решение «какой текст,
 * какой цвет и что делает кнопка». Как чистая функция оно проверяется тестом, а
 * не глазами по рендеру.
 *
 * **Экран больше не говорит о защите.** Проба защиты остаётся заглушкой
 * (`UnavailableProbe` всегда возвращает `ProbeUnavailable`), поэтому блок
 * «Защита» и тексты «трафик идёт через туннель / проверка не прошла» ничего не
 * измеряли и только сбивали с толку. Пользователь просил ровно два, и оба
 * честно выводимы из состояния туннеля: подключено или нет и какой конфиг
 * работает. Доменный механизм защиты при этом сохранён — [ConnectionStatus.Protected]
 * и [ConnectionStatus.ProtectionFailed] по-прежнему существуют, их просто не
 * различает подача.
 */
data class StatusPresentation(
    val title: String,
    val detail: String,
    val accent: Color,
    val ring: RingTone,
    /** Текст главной кнопки. Матрица кнопки — из `docs/design/mockup.html`. */
    val actionLabel: String,
    /** Что делает главная кнопка. */
    val action: StatusAction,
)

/**
 * Действие главной кнопки.
 *
 * Типом, а не лямбдой: экран должен решать, что вызвать, а тест — проверять, что
 * в этом состоянии предложено именно это действие. Лямбда в презентации
 * протащила бы зависимость на ViewModel в чистую функцию.
 */
enum class StatusAction {
    /** Поднять туннель. */
    Connect,

    /** Прервать попытку. Отличается от [Disconnect]: отключать ещё нечего. */
    Cancel,

    /** Опустить туннель. */
    Disconnect,

    /** Повторить попытку после сбоя. */
    Retry,

    /** Открыть системные настройки: без разрешения подключиться нельзя. */
    OpenSettings,

    /** Обновить данные подписки. НЕ ведёт к покупке — это анти-стеринг 3.1.1. */
    RefreshAccess,
}

/**
 * Сопоставление состояния и подачи.
 *
 * Три состояния «туннель поднят» — [ConnectionStatus.VerifyingProtection],
 * [ConnectionStatus.Protected] и [ConnectionStatus.ProtectionFailed] — показываются
 * одинаково: «Подключено». Для интерфейса это одно и то же — интерфейс поднят, —
 * а различить их честно нельзя: проба защиты не подтверждает ничего, и выдавать
 * «защищено» было бы той ложной уверенностью, против которой написан §6.
 *
 * Матрица кнопки взята из макета дословно, включая неочевидные случаи:
 *  - в состоянии «подключение» кнопка «Отменить», а не «Отключить»: раньше
 *    предлагалось отключить то, чего ещё нет;
 *  - в состоянии «нет разрешения» кнопка ведёт в настройки, потому что обойти
 *    системный диалог нельзя;
 *  - «обновить доступ» не ведёт к покупке.
 *
 * [runningConfigName] — имя работающего подключения, если известно. Показывается
 * подзаголовком в состояниях «туннель поднят», потому что пользователь просил
 * знать, какой конфиг работает. `null` — имени нет, подзаголовок нейтрален.
 *
 * [bypassCount] — сколько сервисов обходится мимо туннеля. Обходы означают, что
 * «Подключено» не значит «защищено всё»: часть трафика уходит напрямую. Молчать
 * об этом — та же ложная уверенность, против которой написан §6. Поэтому при
 * `bypassCount > 0` подзаголовок прямо говорит о частичном обходе.
 *
 * [bypassSupported] — применяет ли ЭТО устройство исключения обходов на самом
 * деле. Исключения делаются через `VpnService.Builder.excludeRoute`, который
 * есть только с Android 13 (API 33); при `minSdk 26` на API 26–32 список
 * обходов записан, но маршруты не исключаются — обходов нет, трафик идёт через
 * туннель. Сказать «часть трафика идёт напрямую» там значило бы соврать в
 * обратную сторону. Поэтому при `bypassCount > 0 && !bypassSupported`
 * подзаголовок честно сообщает о недоступности обхода, а не о его работе.
 *
 * Дефолт `bypassSupported = false` — безопасная сторона: неизвестность склоняем
 * в сторону «обход не действует». Обратный дефолт (`true`) заставлял бы
 * забывшего аргумент вызывающего обещать работающий обход, которого может не
 * быть, — недоказанное утверждение, запрещённое §6.
 */
fun ConnectionStatus.presentation(
    runningConfigName: String? = null,
    bypassCount: Int = 0,
    bypassSupported: Boolean = false,
): StatusPresentation = when (this) {
    ConnectionStatus.Disconnected -> StatusPresentation(
        title = "Не подключено",
        detail = "Выберите подключение и нажмите «Подключить»",
        // Нейтральный, не красный: выключенное состояние — это не ошибка.
        accent = VpnColors.TextSecondary,
        ring = RingTone.Idle,
        actionLabel = "Подключить",
        action = StatusAction.Connect,
    )

    ConnectionStatus.Connecting -> StatusPresentation(
        title = "Подключение",
        detail = "Устанавливаем соединение",
        // Янтарный — только идущий процесс.
        accent = VpnColors.Amber,
        ring = RingTone.Process,
        actionLabel = "Отменить",
        action = StatusAction.Cancel,
    )

    // Туннель поднят. Три доменных исхода различимы внутри, но пользователю
    // показывается одно: соединение есть. Спокойный нейтральный тон — это
    // подключённость, а не защищённость, и заголовок это подтверждает словами.
    ConnectionStatus.VerifyingProtection,
    is ConnectionStatus.Protected,
    is ConnectionStatus.ProtectionFailed,
    -> StatusPresentation(
        title = "Подключено",
        detail = if (bypassCount > 0) {
            // Обходы записаны, но применяются не везде. На API < 33
            // `excludeRoute` не существует, и заявлять о работающем обходе было
            // бы ложью наоборот: трафик на самом деле идёт через туннель.
            if (bypassSupported) {
                // Обходы означают, что часть трафика идёт мимо туннеля. Молчать об
                // этом нельзя: «Подключено» иначе читается как «защищено всё».
                "Подключено, часть трафика идёт напрямую: сервисов — $bypassCount"
            } else {
                // Не молчим и не врём: обход есть в списке, но системой не
                // применяется — прямо говорим, что он недоступен здесь.
                "Подключено. Обход недоступен на этой версии Android"
            }
        } else {
            runningConfigName ?: "Соединение установлено"
        },
        accent = VpnColors.Mist,
        ring = RingTone.Verifying,
        actionLabel = "Отключить",
        action = StatusAction.Disconnect,
    )

    is ConnectionStatus.Failed -> StatusPresentation(
        title = "Не удалось подключиться",
        detail = reason,
        // Красный: подключение не состоялось, и это видно пользователю.
        accent = VpnColors.Red,
        ring = RingTone.Danger,
        actionLabel = "Повторить",
        action = StatusAction.Retry,
    )
}
