package com.impossi8le.vpnapp.feature.home

/**
 * Подпись о том, что список подключений показан из кэша, — или `null`.
 *
 * **Зачем это здесь, а не «просто показываем сохранённое».**
 * Кэш держит список на экране, пока идёт обновление, и это удобно: пользователь
 * заходит и сразу видит, что выбрать. Но сохранённый список — это НЕ текущее
 * состояние подписки, и молча выдать его за свежий значит утверждать то, чего мы
 * не проверяли. Инвариант §6 запрещает показывать непроверенное состояние как
 * проверенное, поэтому пока данные из кэша и свежий ответ ещё не пришёл, экран
 * обязан сказать об этом прямо.
 *
 * Чистая функция, а не строка в разметке: «что и когда писать» — это решение, и
 * его проверяет тест.
 *
 * @param fromCache показан ли список из кэша (в этом сеансе обновление ещё не
 *   завершилось успехом).
 * @param refreshing идёт ли сейчас обновление из сети. Пока идёт, отдельная
 *   подпись не нужна: на экране уже стоит индикатор «Идёт обновление…», и второй
 *   строкой про то же самое было бы только шумом. Подпись о кэше — это состояние
 *   ПОКОЯ: данные сохранённые, обновление не идёт.
 * @return текст подписи или `null`, если говорить нечего.
 *
 * Тон — «могут быть устаревшими», а не «устарели»: за время с прошлого ответа
 * список мог и не измениться, и уверенно называть кэш старым значило бы врать в
 * обратную сторону. Здесь ровно то, что мы знаем: данные сохранённые.
 */
fun stalenessNote(fromCache: Boolean, refreshing: Boolean): String? = when {
    !fromCache -> null
    refreshing -> null
    else -> "Показаны сохранённые данные, они могут быть устаревшими"
}
