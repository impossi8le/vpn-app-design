package com.impossi8le.vpnapp.feature.home

/**
 * Что выделить в списке подключений, когда выбора ещё нет.
 *
 * На чистой установке `selectedConfigId` пуст, и список показывался без единой
 * выделенной строки: непонятно ни что работает, ни с чем подключаться. Функция
 * закрывает ровно этот случай и ничего больше.
 *
 * **«Первый» — это порядок сервера, а не свежесть.** `toRowStates` сохраняет
 * порядок ответа `/me` намеренно, и сортировка здесь была бы вторым мнением о
 * том, что важнее. Признака свежести у строки нет — есть только срок окончания,
 * а «выбрать то, что истекает позже» не то же самое, что «выбрать то, что
 * первым предложил сервер»: при равных подписках это произвольная перестановка.
 * Поэтому берём первый подходящий как он лежит.
 *
 * **Сохранённый выбор не перебивается.** Если [currentId] не `null` — он и
 * возвращается. Автовыбор обязан срабатывать только на пустом выборе: иначе
 * после перезапуска пользователь получил бы не своё подключение, а чужое.
 *
 * **Мёртвое не выделяется.** [ConfigRowStatus.Expired] значит «подписка
 * кончилась» — подсветить такую строку значило бы обещать работу, которой не
 * будет. Если живых нет вовсе, возвращается `null`: честное «выбирать нечего».
 *
 * Время и сеть функции не нужны — только список и текущий id, поэтому тест
 * детерминирован и не требует Android.
 */
fun pickDefaultConfigId(candidates: List<ConfigRowState>, currentId: String?): String? {
    if (currentId != null) return currentId
    return candidates.firstOrNull { it.status != ConfigRowStatus.Expired }?.id
}
