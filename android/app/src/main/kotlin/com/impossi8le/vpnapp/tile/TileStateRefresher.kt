package com.impossi8le.vpnapp.tile

import com.impossi8le.vpnapp.domain.tunnel.TunnelState
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.launch

/**
 * Перерисовка плитки, пока шторка «Быстрых настроек» открыта.
 *
 * **Зачем.** `TileService` не получает обратных вызовов об изменении состояния:
 * систему никто не просит опросить плитку. Прежняя реализация читала состояние
 * ровно дважды — в `onStartListening` и сразу после `onClick` — и этого мало:
 * пока шторка открыта, сервис публикует `CONNECTING` и `ESTABLISHED`, но плитка
 * их не видит. Подпись замирала на прочитанном при открытии, и тумблер выглядел
 * сломанным: нажал — а «отключён» остался «отключён» (issue #53).
 *
 * Второй след того же: `onClick` рисует НЕМЕДЛЕННО после
 * `startForegroundService()`, то есть до того, как сервис что-либо опубликовал.
 * В хранилище в этот момент лежит `Unknown`, и плитка честно рисует
 * «состояние неизвестно», хотя тап уже сработал. Подписка закрывает и это: как
 * только сервис сообщит настоящее состояние, плитка перерисуется сама.
 *
 * **Почему подписка, а не опрос.** Опрос раз в несколько секунд показывал бы
 * процесс «подключение…» с опозданием и снова замирал бы между тиками. Поток
 * отдаёт кадр ровно на каждое изменение, и `StateFlow` при подписке сразу даёт
 * текущее значение — отдельный первый кадр не нужен.
 *
 * **Почему отдельный тип, а не цикл внутри сервиса.** Решение «когда перерисовать»
 * проверяется тестом на виртуальном времени; `TileService` так проверить нельзя —
 * его поднимает только система.
 */
class TileStateRefresher {

    private var job: Job? = null

    /**
     * Подписаться на состояние и рисовать каждое изменение.
     *
     * @param states поток состояния туннеля; при подписке сразу отдаёт текущее.
     * @param onState куда отдать состояние для перерисовки.
     */
    fun start(
        scope: CoroutineScope,
        states: StateFlow<TunnelState>,
        onState: (TunnelState) -> Unit,
    ) {
        // Прежнюю подписку снимаем ВСЕГДА: `onStartListening` зовётся на каждое
        // открытие шторки, и без отмены они копились бы по одной на открытие.
        job?.cancel()
        job = scope.launch {
            states.collect(onState)
        }
    }

    /**
     * Отписаться. Зовётся из `onStopListening`: шторка закрыта — рисовать некому,
     * и живая подписка дёргала бы систему без предмета.
     */
    fun stop() {
        job?.cancel()
        job = null
    }
}
