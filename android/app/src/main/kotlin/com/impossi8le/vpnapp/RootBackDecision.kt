package com.impossi8le.vpnapp

/**
 * Что делать по жесту «Назад» на экране, где возвращаться некуда.
 *
 * Правило вынесено из [AppRoot] чистой функцией: решение «свернуть или
 * показать подсказку» — это логика, и проверять её надо тестом, а не рендером.
 * Причин две, и обе про честность поведения:
 *
 * 1. **«Назад» не должен выглядеть сломанным.** Прежний `BackHandler(enabled =
 *    true) { back() }` всегда забирал событие себе, а на корневом экране делать
 *    было нечего — кнопка молчала. Комментарий рядом обещал, что событие уйдёт
 *    системе, но `BackHandler` так не умеет: он либо перехватывает, либо
 *    выключен. Забрать событие и ничего не сделать — худший вариант.
 * 2. **Двойной жест — не закрытие, а сворачивание.** Приложение нельзя
 *    «закрыть» случайным свайпом: под туннелем может идти трафик. Поэтому
 *    первый жест лишь объясняет, что произойдёт, и только повторный —
 *    сворачивает (не завершает) приложение.
 *
 * **Почему время приходит параметром.** Момент «сейчас» влияет на то, считается
 * ли жест двойным, и если читать часы внутри, тест перестанет быть
 * детерминированным, а функция — чистой. Передавая `nowMs`, мы получаем один и
 * тот же результат на любом запуске.
 */
sealed interface BackDecision {

    /** Есть куда вернуться — обычный возврат на предыдущий экран. */
    data object NavigateBack : BackDecision

    /** Возвращаться некуда: показать, что приложение свернётся, а не закроется. */
    data object ShowMinimizeNotice : BackDecision

    /** Возвращаться некуда и жест повторён — свернуть приложение в фон. */
    data object Minimize : BackDecision
}

/**
 * Окно, в течение которого повторный жест считается двойным.
 *
 * Две секунды — как у системного «нажмите ещё раз, чтобы выйти»: достаточно,
 * чтобы успеть осознанно повторить, и мало, чтобы случайный повтор через
 * полминуты свернул приложение вопреки намерению.
 */
const val MINIMIZE_NOTICE_WINDOW_MS = 2_000L

/**
 * Решение о том, что делать по жесту «Назад».
 *
 * @param canNavigateBack есть ли куда вернуться (непустой стек навигации);
 * @param nowMs текущее монотонное время;
 * @param lastMinimizeNoticeAtMs время, когда на корневом экране показывали
 *   подсказку; `0` — подсказки ещё не было (монотонное время до нуля не
 *   опускается, потому `0` — безопасный признак «не было»);
 * @param windowMs окно двойного жеста.
 */
fun decideBack(
    canNavigateBack: Boolean,
    nowMs: Long,
    lastMinimizeNoticeAtMs: Long,
    windowMs: Long = MINIMIZE_NOTICE_WINDOW_MS,
): BackDecision = when {
    // Возврат всегда важнее сворачивания: если есть история, «Назад» ведёт по ней.
    canNavigateBack -> BackDecision.NavigateBack

    // Повтор в пределах окна. Проверка `>= 0` отсекает случай, когда часы
    // «поехали» назад: тогда жест считается первым, а не двойным, — сработать
    // мимо намерения хуже, чем не сработать вовсе.
    lastMinimizeNoticeAtMs != 0L &&
        (nowMs - lastMinimizeNoticeAtMs) in 0..windowMs -> BackDecision.Minimize

    else -> BackDecision.ShowMinimizeNotice
}
